"""Generation records and their session-scoped projections. Reads use SQLite alone."""
import json
from contextlib import contextmanager

from .domain import Missing

DDL = (
    """CREATE TABLE generation(
       id INTEGER PRIMARY KEY, session_id TEXT NOT NULL REFERENCES session,
       snapshot_id TEXT NOT NULL REFERENCES snapshot, section TEXT NOT NULL,
       request_id TEXT NOT NULL, cache_key TEXT NOT NULL, question TEXT, body TEXT NOT NULL DEFAULT '',
       status TEXT NOT NULL CHECK(status IN ('running','complete','failed','cancelled','interrupted')),
       origin TEXT NOT NULL DEFAULT 'standalone', format TEXT NOT NULL,
       settings TEXT NOT NULL, prompt_version TEXT NOT NULL, evidence TEXT NOT NULL,
       usage TEXT, error TEXT, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
       updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(session_id, request_id))""",
    "CREATE INDEX generation_cache ON generation(cache_key,status,id)",
    """CREATE TABLE artifact_link(session_id TEXT NOT NULL REFERENCES session,
       generation_id INTEGER NOT NULL REFERENCES generation, PRIMARY KEY(session_id,generation_id))""",
    """CREATE TRIGGER link_boundary BEFORE INSERT ON artifact_link
       WHEN NOT EXISTS(SELECT 1 FROM generation g JOIN session s ON s.snapshot_id=g.snapshot_id
                       WHERE g.id=NEW.generation_id AND s.id=NEW.session_id AND g.section!='chat')
       BEGIN SELECT RAISE(ABORT,'snapshot mismatch'); END""",
    """CREATE VIEW message AS
       SELECT id*2 AS sequence,session_id,request_id,'user' AS role,question AS content,
       'complete' AS status,'user' AS origin,created_at FROM generation WHERE section='chat'
       UNION ALL SELECT id*2+1,session_id,request_id,'assistant',body,status,origin,updated_at
       FROM generation WHERE section='chat'""",
)


def unpack(row):
    item = dict(row)
    for field in ("settings", "evidence", "usage"):
        if item[field] is not None:
            item[field] = json.loads(item[field])
    return item


def linked(db, sid, section, version=None):
    sql = """SELECT g.* FROM generation g JOIN artifact_link a ON a.generation_id=g.id
             WHERE a.session_id=? AND g.section=?"""
    args = [sid, section]
    if version is not None:
        sql += " AND g.id=?"
        args.append(version)
    # Prefer the most recently selected completed version. Failed attempts remain inspectable by ID.
    row = db.execute(sql + " ORDER BY (status='complete') DESC,a.rowid DESC LIMIT 1", args).fetchone()
    if row is None:
        raise Missing("No saved version of this section in this session.")
    return dict(unpack(row), session_id=sid)


def history(db, sid):
    return [dict(row) for row in db.execute("SELECT * FROM message WHERE session_id=? ORDER BY sequence", (sid,))]


def resume(db, sid):
    from .persistence import session
    metadata = session(db, sid)
    rows = db.execute("""SELECT g.id,g.section,g.status,g.format FROM artifact_link a
                       JOIN generation g ON g.id=a.generation_id WHERE a.session_id=? ORDER BY a.rowid""", (sid,))
    artifacts = [dict(row) for row in rows]
    messages = history(db, sid)
    if artifacts or messages:
        metadata.update(artifacts=artifacts, messages=messages)
    return metadata


def saved(db, sid):
    from .persistence import session
    metadata = session(db, sid)
    rows = db.execute("""SELECT g.* FROM generation g JOIN artifact_link a ON a.generation_id=g.id
                       WHERE a.session_id=? ORDER BY a.rowid""", (sid,))
    artifacts = [dict(unpack(row), session_id=sid) for row in rows]
    answers = [unpack(row) for row in db.execute(
        "SELECT * FROM generation WHERE session_id=? AND section='chat' ORDER BY id", (sid,))]
    return dict(session=metadata, artifacts=artifacts, messages=history(db, sid), exchanges=answers)


def render(data, fmt):
    if fmt == "json":
        return json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    if fmt != "markdown":
        raise ValueError("Select markdown, json or mermaid.")
    output = [f"# CodeLens session {data['session']['session_id']}", f"Snapshot: {data['session']['snapshot_id']}"]
    for r in [*data["artifacts"], *data["exchanges"]]:
        output.extend([f"## {r['section']} · version {r['id']} ({r['status']})",
                       f"Generated by {r['settings']['provider']} / {r['settings']['model']}"])
        if r["question"]:
            output.append(r["question"])
        if r["format"] == "mermaid":
            output.append("```mermaid\n" + r["body"] + "\n```")
        else:
            output.append(r["body"])
        if r["error"]:
            output.append(r["error"])
        for e in r["evidence"]:
            output.append(f"### [{e['label']}] {e['path']}:L{e['start']}-L{e['end']}\n\n" +
                          "\n".join("    " + line for line in e["text"].splitlines()))
    return "\n\n".join(output) + "\n"


@contextmanager
def session_lock(locations, sid):
    # sid has already been resolved against the session table.
    import fcntl
    locks = locations.data / "locks"
    locks.mkdir(mode=0o700, exist_ok=True)
    with (locks / sid).open("a") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            yield False
        else:
            yield True


def interrupted(db, sid):
    db.execute("""UPDATE generation SET status='interrupted',error='Process exited before completion.',
               updated_at=CURRENT_TIMESTAMP WHERE session_id=? AND status='running'""", (sid,))


def recover(db, locations, sid):
    if db.execute("SELECT 1 FROM generation WHERE status='running' AND session_id=?", (sid,)).fetchone():
        with session_lock(locations, sid) as acquired:
            if acquired:
                interrupted(db, sid)
